// Generates the C# exercise database for the MAUI port from the TypeScript source of truth.
//
//   node maui/scripts/generate-exercises.mjs      (from the repo root)
//
// Outputs:
//   maui/GymBuddy.Core/Data/BuiltInExercises.g.cs  ← src/data/exercises.ts (BUILT_IN_EXERCISES, source order)
//   maui/GymBuddy.Core/Data/ExerciseImages.g.cs    ← the folders in assets/exercises/<id>/ (sorted)
//   maui/GymBuddy.Tests/Fixtures/built-in-library.json ← the TS app's library export of the built-ins
//     (JSON.stringify(file, null, 2), fixed exportedAt), so a test can check that the C# export is byte-identical.
//
// Uses only Node built-ins and the repo's `typescript` package. Fails loudly when the exercise
// count is not the expected one, or when the data contains a value the C# enums do not know.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const EXPECTED_COUNT = 123;

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const require = createRequire(path.join(repo, 'package.json'));
const ts = require('typescript');

const MUSCLES = ['chest', 'front_delts', 'side_delts', 'rear_delts', 'lats', 'upper_back', 'traps', 'lower_back', 'biceps',
  'triceps', 'forearms', 'abs', 'obliques', 'quads', 'hamstrings', 'glutes', 'adductors', 'hip_flexors', 'calves'];
const EQUIPMENT = ['barbell', 'dumbbell', 'kettlebell', 'cable', 'machine', 'smith_machine', 'ez_bar', 'band', 'bench', 'rack',
  'pull_up_bar', 'dip_station', 'bodyweight'];
const PATTERNS = ['horizontal_push', 'vertical_push', 'horizontal_pull', 'vertical_pull', 'squat', 'hinge', 'lunge', 'carry',
  'core', 'isolation'];

function fail(message) {
  console.error(`generate-exercises: ${message}`);
  process.exit(1);
}

/** "front_delts" → "FrontDelts" (the C# enum member for a slug). */
function pascal(slug, known, kind) {
  if (!known.includes(slug)) fail(`unknown ${kind} '${slug}'`);
  return slug.split('_').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
}

/** C# string literal with the exact text (JSON escapes are valid C# escapes). */
function str(s) {
  if (typeof s !== 'string') fail(`expected a string, got ${JSON.stringify(s)}`);
  return JSON.stringify(s);
}

/** Shortest round-trip number text, like JavaScript's String(n); always a valid C# double literal. */
function num(n) {
  if (typeof n !== 'number' || !Number.isFinite(n)) fail(`expected a number, got ${JSON.stringify(n)}`);
  const s = String(n);
  if (/e/i.test(s)) fail(`unexpected exponent notation ${s}`);
  return s;
}

async function loadExercises() {
  const source = fs.readFileSync(path.join(repo, 'src/data/exercises.ts'), 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, verbatimModuleSyntax: false },
    fileName: 'exercises.ts',
  });
  if (/^\s*import\s/m.test(outputText)) fail('the transpiled module still has an import; only type-only imports are supported');
  const url = `data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`;
  const mod = await import(url);
  return mod.BUILT_IN_EXERCISES;
}

function exerciseCs(e) {
  const muscles = Object.entries(e.muscles)
    .map(([m, v]) => `[MuscleGroup.${pascal(m, MUSCLES, 'muscle')}] = ${num(v)}`)
    .join(', ');
  const equipment = e.equipment.map((x) => `Equipment.${pascal(x, EQUIPMENT, 'equipment')}`).join(', ');
  if (typeof e.compound !== 'boolean') fail(`${e.id}: compound is not a boolean`);
  if (!Number.isInteger(e.difficulty)) fail(`${e.id}: difficulty is not an integer`);
  return [
    '        new Exercise',
    '        {',
    `            Id = ${str(e.id)},`,
    `            Name = ${str(e.name)},`,
    `            Equipment = [${equipment}],`,
    `            Pattern = MovementPattern.${pascal(e.pattern, PATTERNS, 'pattern')},`,
    `            Compound = ${e.compound},`,
    `            Muscles = new Dictionary<MuscleGroup, double> { ${muscles} },`,
    `            Difficulty = ${e.difficulty},`,
    `            Cues = [${e.cues.map(str).join(', ')}],`,
    '        },',
  ].join('\n');
}

const exercises = await loadExercises();
if (!Array.isArray(exercises)) fail('BUILT_IN_EXERCISES is not an array');
if (exercises.length !== EXPECTED_COUNT) {
  fail(`expected ${EXPECTED_COUNT} exercises, found ${exercises.length}. Update EXPECTED_COUNT here and in the C# tests deliberately.`);
}
const ids = new Set();
for (const e of exercises) {
  if (ids.has(e.id)) fail(`duplicate id ${e.id}`);
  ids.add(e.id);
}

const exercisesCs = `// GENERATED by maui/scripts/generate-exercises.mjs from src/data/exercises.ts — do not edit.
// Re-run: node maui/scripts/generate-exercises.mjs (from the repo root).
namespace GymBuddy.Core.Data;

/// <summary>The built-in exercise database (${EXPECTED_COUNT} entries, in the order of src/data/exercises.ts).</summary>
public static class BuiltInExercises
{
    public const int Count = ${EXPECTED_COUNT};

    public static readonly IReadOnlyList<Exercise> All = new Exercise[]
    {
${exercises.map(exerciseCs).join('\n')}
    };
}
`;

const imagesDir = path.join(repo, 'assets/exercises');
const photoIds = fs
  .readdirSync(imagesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const photos = photoIds.map((id) => {
  const files = fs.readdirSync(path.join(imagesDir, id)).filter((f) => /^\d+\.jpg$/.test(f)).sort();
  if (files.length === 0) fail(`assets/exercises/${id} has no photos`);
  if (!ids.has(id)) fail(`assets/exercises/${id} does not match a built-in exercise id`);
  return { id, files };
});

const imagesCs = `// GENERATED by maui/scripts/generate-exercises.mjs from the folders in assets/exercises — do not edit.
// Re-run: node maui/scripts/generate-exercises.mjs (from the repo root).
namespace GymBuddy.Core.Data;

/// <summary>
/// Exercises that have demonstration photos (start / end position) bundled from the public-domain
/// free-exercise-db dataset. The app bundles them as MauiAssets named "exercises/&lt;id&gt;/0.jpg".
/// </summary>
public static class ExerciseImages
{
    private static readonly Dictionary<string, string[]> Files = new(StringComparer.Ordinal)
    {
${photos.map((p) => `        [${str(p.id)}] = [${p.files.map((f) => str(`exercises/${p.id}/${f}`)).join(', ')}],`).join('\n')}
    };

    /// <summary>Ids with photos, sorted ordinally.</summary>
    public static readonly IReadOnlyCollection<string> IdsWithPhotos = Files.Keys.ToArray();

    public static bool HasPhotos(string id) => Files.ContainsKey(id);

    /// <summary>The asset names of the photos ("exercises/&lt;id&gt;/0.jpg", "exercises/&lt;id&gt;/1.jpg"), empty when there are none.</summary>
    public static IReadOnlyList<string> AssetPaths(string id) => Files.TryGetValue(id, out var paths) ? paths : Array.Empty<string>();
}
`;

const outDir = path.join(repo, 'maui/GymBuddy.Core/Data');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'BuiltInExercises.g.cs'), exercisesCs);
fs.writeFileSync(path.join(outDir, 'ExerciseImages.g.cs'), imagesCs);
const fixtureDir = path.join(repo, 'maui/GymBuddy.Tests/Fixtures');
fs.mkdirSync(fixtureDir, { recursive: true });
const libraryFile = { format: 'gym-buddy-exercises', version: 2, exportedAt: '2026-01-01T00:00:00.000Z', exercises };
fs.writeFileSync(path.join(fixtureDir, 'built-in-library.json'), JSON.stringify(libraryFile, null, 2));

console.log(`generate-exercises: ${exercises.length} exercises, ${photos.length} with photos`);
