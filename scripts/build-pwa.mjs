// Turns the `expo export -p web` output in dist/ into an installable, offline-capable PWA:
// injects the manifest/icon/theme tags and the service-worker registration into index.html,
// adds the GitHub Pages SPA fallback (404.html, .nojekyll) and generates dist/sw.js.
//
// Usage: node scripts/build-pwa.mjs   (after `expo export -p web`; see `npm run build:web`)
// WEB_BASE_URL (e.g. `/gym-buddy`) must match the value the export was built with.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
const THEME_COLOR = '#FFFFFF';
const FONT_EXT = /\.(ttf|otf|woff2?)$/i;
const IMAGE_EXT = /\.(jpe?g|png|webp|gif|svg|avif)$/i;
/** Never precached: the worker itself, the 404 copy of the shell, export metadata. */
const NOT_PRECACHED = new Set(['sw.js', '404.html', 'metadata.json', '.nojekyll']);

function normalizeBase(raw) {
  const trimmed = (raw ?? '').trim().replace(/\/+$/, '');
  if (!trimmed) return '';
  return trimmed.startsWith('/') ? trimmed : `/${trimmed}`;
}

/** All files under dir, as POSIX paths relative to dir, sorted. */
function listFiles(dir) {
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const full = join(d, name);
      if (statSync(full).isDirectory()) walk(full);
      else out.push(relative(dir, full).split(sep).join('/'));
    }
  };
  walk(dir);
  return out.sort();
}

const base = normalizeBase(process.env.WEB_BASE_URL);
const indexPath = join(DIST, 'index.html');
if (!existsSync(indexPath)) {
  console.error(`build-pwa: ${indexPath} not found. Run \`expo export -p web\` first.`);
  process.exit(1);
}

// 1. index.html head tags. Hrefs are absolute (base-prefixed) because the same file is served as
//    404.html for deep links such as /gym-buddy/plan/abc.
let html = readFileSync(indexPath, 'utf8');
if (html.includes('rel="manifest"')) {
  console.error('build-pwa: index.html already has a manifest link (ran twice?). Re-run the export first.');
  process.exit(1);
}
const registration = `window.addEventListener('load',function(){if('serviceWorker' in navigator){navigator.serviceWorker.register('${base}/sw.js',{scope:'${base}/'}).catch(function(e){console.warn('Service worker registration failed',e);});}if(navigator.storage&&navigator.storage.persist){navigator.storage.persist().catch(function(){});}});`;
const headTags = [
  `<link rel="manifest" href="${base}/manifest.webmanifest">`,
  `<meta name="theme-color" content="${THEME_COLOR}">`,
  '<meta name="mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-status-bar-style" content="default">',
  `<link rel="apple-touch-icon" href="${base}/icons/apple-touch-icon.png">`,
  `<script>${registration}</script>`,
].join('\n    ');
if (!html.includes('</head>')) {
  console.error('build-pwa: no </head> in index.html');
  process.exit(1);
}
html = html.replace('</head>', `    ${headTags}\n  </head>`);
writeFileSync(indexPath, html);

// 2. GitHub Pages: SPA fallback for deep links, and no Jekyll processing (it would drop `_expo/`).
copyFileSync(indexPath, join(DIST, '404.html'));
writeFileSync(join(DIST, '.nojekyll'), '');

// 3. Service worker.
const files = listFiles(DIST).filter((f) => f !== 'sw.js');
const hash = createHash('sha256');
for (const f of files) {
  hash.update(f);
  hash.update('\0');
  hash.update(readFileSync(join(DIST, f)));
  hash.update('\0');
}
const cacheName = `gym-buddy-${hash.digest('hex').slice(0, 16)}`;

// Encode exactly like the browser does (WHATWG path rules keep `[` `]`, which encodeURI would escape),
// so the precache keys match the URLs the page actually requests, e.g. the `[id]-<hash>.js` route chunks.
const url = (path) => base + new URL(path, 'http://x/').pathname;
const shell = [`${base}/`];
const images = [];
for (const f of files) {
  if (NOT_PRECACHED.has(f)) continue;
  if (f.startsWith('assets/') && IMAGE_EXT.test(f)) images.push(url(f));
  else if (
    f === 'index.html' ||
    f === 'manifest.webmanifest' ||
    f === 'favicon.ico' ||
    f.startsWith('_expo/static/') ||
    f.startsWith('icons/') ||
    (f.startsWith('assets/') && FONT_EXT.test(f))
  )
    shell.push(url(f));
}
const unclassified = files.filter(
  (f) => !NOT_PRECACHED.has(f) && !shell.includes(url(f)) && !images.includes(url(f)),
);

const sw = `// Generated by scripts/build-pwa.mjs. Do not edit.
// A new deploy gets a new CACHE name. There is deliberately no skipWaiting(): the new worker waits
// until every app window is closed, because an open old page may still lazy-load its own hashed chunks.
const CACHE = ${JSON.stringify(cacheName)};
const INDEX = ${JSON.stringify(`${base}/index.html`)};
/** App shell: must all be cached for the install to succeed. */
const SHELL = ${JSON.stringify(shell, null, 2)};
/** Exercise photos: cached best effort, a missing one does not block installation. */
const IMAGES = ${JSON.stringify(images, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await cache.addAll(SHELL);
      await Promise.allSettled(IMAGES.map((url) => cache.add(url)));
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(names.filter((name) => name !== CACHE).map((name) => caches.delete(name)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // Single-page app: every route is rendered by index.html.
    event.respondWith(
      (async () => {
        const cached = await caches.match(INDEX, { cacheName: CACHE });
        return cached || fetch(request);
      })(),
    );
    return;
  }

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(request, { ignoreSearch: true });
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok && response.type === 'basic') {
        cache.put(request, response.clone()).catch(() => {});
      }
      return response;
    })(),
  );
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);

// 4. Summary.
const bytes = (urls) =>
  urls.reduce((sum, u) => {
    const path = decodeURIComponent(u.slice(base.length + 1)) || 'index.html';
    return sum + statSync(join(DIST, path)).size;
  }, 0);
const mb = (n) => `${(n / 1024 / 1024).toFixed(1)} MB`;
console.log(`build-pwa: base "${base || '/'}", cache ${cacheName}`);
console.log(`  shell:  ${shell.length} URLs, ${mb(bytes(shell))} (required)`);
console.log(`  images: ${images.length} URLs, ${mb(bytes(images))} (best effort)`);
if (unclassified.length) console.log(`  not precached: ${unclassified.join(', ')}`);
console.log('  wrote index.html tags, 404.html, .nojekyll, sw.js');
